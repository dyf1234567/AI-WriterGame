TIER_B = """【城市与社会背景（B层一句话）】魔都：南方金融之都——龙脊CBD（电竞解说车车与灵儿、退役女团炭炭、明星剧组常驻）、外滩滨江（青梅竹马郭瑞莹读音乐学院、明星散步圣地）、星愿游乐园（约会圣地）、渔人码头（吃不饱与吐泡泡的主场）、云顶天文台；十余位明星歌手（杨幂/刘亦菲/宋轶/杨超越/章若楠/赵丽颖/赵今麦/迪丽热巴/张靓颖/邓紫棋/鞠婧祎/单依纯）行程全球、常驻魔都；京都站↔魔都南站高铁约两小时；网络那头还有一群网友（邓碧瑶/乌苏苏/乐乐/歪歪/小新/慕慕）。社会背景：普通现代都市社会——绩点、实习、热搜与烟火；超凡没有成为公开社会秩序，"系统"仍是主角自己的秘密。其他城市与国家可随玩家选择进入，校园不是人生的边界。"""

# C层条目：(展开全文, 关键词行, 展开条件——人物名或地点名任一命中即展开)

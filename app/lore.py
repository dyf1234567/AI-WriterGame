EXTRA_RULES = """纪年为公元现代。人物关系由利益、情感与具体事件决定，没有固定善恶阵营；NPC 只知道自己通过合理渠道获得的信息。所有角色均为成年人；感情线可以并行暧昧，但每一步靠近都要有剧情因果。另有一条隐秘线：心动系统的深层沉睡着「灵能觉醒」——修仙之力只属于主角一人，都市之中再无第二个修行者，也无修行界；主角的修炼必须瞒着所有人进行。"""


def canon_block(state: dict | None = None) -> str:
    """注入系统提示词的世界正典块。state 提供接触状态：C 层只在相关人物/地点
    已进入玩家视野时展开全文，否则以关键词行带过。"""
    known_names: set[str] = set()
    if state:
        known_names |= {n.get("name", "") for n in state.get("npcs", [])
                        if n.get("known_to_player", n.get("last_seen_turn", -1) >= 0)}
        known_names |= {p.get("name", "") for p in state.get("map", {}).get("urban", [])
                        if p.get("discovered")}
    c_lines = []
    for full, hint, keys in _TIER_C_ITEMS:
        c_lines.append(full if any(k in known_names for k in keys) else hint)
    tier_c = ("【隐秘与传闻（C层·只按已接触范围展开；未接触条目仅为传闻关键词，"
              "不得展开细节或主动安排揭示）】\n" + "\n".join("- " + x for x in c_lines))
    return "\n".join([TIER_A, TIER_B, tier_c, EXTRA_RULES])

"""世界正典（分层注入，防提示词膨胀）。

A 层：青临市当前区域细节——主角活动范围，每回合必带。
B 层：城市与社会背景一句话——更广的舞台，每回合以紧凑形式携带。
C 层：隐秘与传闻——**按接触状态分层**：相关人物已认识或地点已探明才展开全文，
      否则只给关键词（"传闻"级），模型不得展开细节。判定依据 npcs[].known_to_player
      与 map[].discovered——信息分层披露的单一事实源在状态里，不在这里另写一套。
"""

TIER_A = """【青临市（唯一世界·A层已细化；主角常在大学城与老城之间）】
滨海大城市，大学城、老城区、商业区、江湾CBD与海岸线共存，地铁与跨海大桥串联全城。
- 青临大学：主角就读的综合性大学，梧桐道、图书馆、食堂、操场；学生会长顾清言、辅导员林慧、神秘留学生白靖都在这里。
- 合租公寓：老城区边缘，主角与室友合住；隔壁是插画师许沁。
- 中央商圈：购物中心、电影院、网红餐厅；宋语棠（隐瞒身份的千金）常出没。
- 滨海老街：咖啡馆、旧书店、琴行与大排档；苏晚晴在琴行兼职，主角的家也在这片。
- 大学城体育馆：各校共享，夜跑与球赛；田径队学妹叶泠的训练地。"""

TIER_B = """【城市与社会背景（B层一句话）】江湾CBD：写字楼森林，沈曼执掌的江湾集团总部所在，实习与兼职的机会之地；青临夜市：码头边的烟火气，小吃与传闻都便宜；星海游乐园与海滨浴场：全城约会圣地；云栖山公园：城郊登山与星空；市立美术馆与回声Livehouse：文艺与地下音乐现场；青临南站：通往其他城市。社会背景：普通现代都市社会——学业绩点、实习内卷、短视频与热搜、邻里烟火；不存在超自然公开现象，"系统"是主角独有的秘密。"""

# C层条目：(展开全文, 关键词行, 展开条件——人物名或地点名任一命中即展开)
_TIER_C_ITEMS = [
    ("云顶天文台的深夜微光（与系统异常信号有关？）",
     "云顶天文台（传闻：深夜亮着微光）", ["云顶天文台"]),
    ("宋氏集团与江湾集团的商业暗流（宋语棠的家世、沈曼的布局）",
     "两大集团的商业暗流（传闻）", ["宋语棠", "沈曼"]),
    ("白靖的交换来得太巧",
     "白靖的来历（传闻：交换的时机太巧）", ["白靖"]),
    ("林慧辅导员的人脉深不可测",
     "林慧的人脉（传闻：深不可测）", ["林慧"]),
    ("顾清言与宋语棠的旧怨",
     "顾清言与宋语棠之间（传闻：似乎有旧怨）", ["顾清言", "宋语棠"]),
]

EXTRA_RULES = """纪年为公元现代。人物关系由利益、情感与具体事件决定，没有固定善恶阵营；NPC 只知道自己通过合理渠道获得的信息。所有角色均为成年人；感情线可以并行暧昧，但每一步靠近都要有剧情因果。"""


def canon_block(state: dict | None = None) -> str:
    """注入系统提示词的世界正典块。state 提供接触状态：C 层只在相关人物/地点
    已进入玩家视野时展开全文，否则以关键词行带过。"""
    known_names: set[str] = set()
    if state:
        known_names |= {n.get("name", "") for n in state.get("npcs", [])
                        if n.get("known_to_player", n.get("last_seen_turn", -1) >= 0)}
        known_names |= {p.get("name", "") for p in state.get("map", {}).get("urban", [])
                        if p.get("discovered")}
    c_lines = []
    for full, hint, keys in _TIER_C_ITEMS:
        c_lines.append(full if any(k in known_names for k in keys) else hint)
    tier_c = ("【隐秘与传闻（C层·只按已接触范围展开；未接触条目仅为传闻关键词，"
              "不得展开细节或主动安排揭示）】\n" + "\n".join("- " + x for x in c_lines))
    return "\n".join([TIER_A, TIER_B, tier_c, EXTRA_RULES])

EXTRA_RULES = """纪年为公元现代。人物关系由利益、情感与具体事件决定，没有固定善恶阵营；NPC 只知道自己通过见证、被告知或公开渠道获得的信息。所有角色均为成年人。感情与事业都由各人决定：高好感不等于同意恋爱，专一、开放或多人关系必须让所有涉及的人知情并同意，任何人都可拒绝或离开。另有可选的隐秘线：心动系统深层沉睡着「灵能觉醒」，都市中也有极少数受距离、疲劳和隐私规则约束的异常感知者。他们没有控制思想、凭空制造财富或替普通人决定人生的能力，也没有支配公开社会的修行界。灯塔观测组研究异常信号，白塔互助会提供匿名健康支持；组织只在玩家主动调查并核实证据后出现，不因普通恋爱、学业或创业强行卷入玩家。忽略、暂停或退出调查不会触发惩罚，不抢走日常生活的焦点。具体线索、调查进度、同意合作与否以 world_sim.mystery 的已结算状态为准，未得到的组织细节不得让普通 NPC 凭空知道。"""


def canon_block(state: dict | None = None) -> str:
    """注入系统提示词的世界正典块。state 提供接触状态：C 层只在相关人物/地点
    已进入玩家视野时展开全文，否则以关键词行带过。"""
    known_names: set[str] = set()
    if state:
        known_names |= {n.get("name", "") for n in state.get("npcs", [])
                        if n.get("known_to_player", n.get("last_seen_turn", -1) >= 0)}
        known_names |= {p.get("name", "") for p in state.get("map", {}).get("urban", [])
                        if p.get("discovered")}
    c_lines = []
    for full, hint, keys in _TIER_C_ITEMS:
        c_lines.append(full if any(k in known_names for k in keys) else hint)
    tier_c = ("【隐秘与传闻（C层·只按已接触范围展开；未接触条目仅为传闻关键词，"
              "不得展开细节或主动安排揭示）】\n" + "\n".join("- " + x for x in c_lines))
    mystery = ((state or {}).get("world_sim") or {}).get("mystery") or {}
    investigated = mystery.get("clues") or []
    mystery_block = "【可选暗线·已核实】" + ("；".join(str(c) for c in investigated)
                         if investigated else "玩家尚未取得调查证据；组织与其他能力者不得直接登场揭底")
    location = ((state or {}).get("player") or {}).get("location") or {}
    city = location.get("city", "京都")
    local = TIER_A
    if city != "京都":
        places = [p for p in ((state or {}).get("map") or {}).get("urban", [])
                  if p.get("city") == city and (p.get("discovered") or p.get("name") == location.get("place"))]
        local = (f"【当前区域：{location.get('country', '华夏')}·{city}】\n"
                 f"主角现在位于{location.get('place') or city}，叙事先落在当地街巷、职业与生活。"
                 "京华大学是既有校园背景，不能因写到旧人而自动返回京都；远方联系人通过实际通信出现。\n"
                 + "\n".join(f"- {p.get('name', '')}：{str(p.get('desc') or '')[:65]}" for p in places[:5]))
    return "\n".join([local, TIER_B, tier_c, EXTRA_RULES, mystery_block])
